package com.demo.agent.config;

import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.info.Contact;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.info.License;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

@Configuration
public class OpenApiConfig {

    @Bean
    public OpenAPI customOpenAPI() {
        return new OpenAPI()
                .info(new Info()
                        .title("Gemini AI Agent API")
                        .version("1.0.0")
                        .description("Enterprise Spring Boot AI Agent integrated with Google Gemini, RAG Knowledge Base, and dynamic REST API execution.")
                        .contact(new Contact()
                                .name("AI Engineering Team")
                                .email("agent-support@example.com"))
                        .license(new License()
                                .name("Apache 2.0")
                                .url("https://www.apache.org/licenses/LICENSE-2.0")));
    }
}
